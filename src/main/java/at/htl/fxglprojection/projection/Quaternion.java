package at.htl.fxglprojection.projection;

public class Quaternion {
    public double w = 0;
    public double x = 0;
    public double y = 0;
    public double z = 0;

    public Quaternion(double w, double x, double y, double z) {
        this.w = w;
        this.x = x;
        this.y = y;
        this.z = z;
    }

    public Quaternion() { }
}
